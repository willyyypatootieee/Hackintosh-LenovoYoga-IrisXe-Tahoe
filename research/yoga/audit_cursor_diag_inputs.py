"""Offline cursor ABI/site audit. Reads captured regular files, never devices."""
from pathlib import Path
import hashlib
import json
import plistlib
import struct
import subprocess

ROOT = Path(__file__).resolve().parent
FB = ROOT / 'installed-signatures-readonly-20261023-233323/copies/data/Library/Extensions/AppleIntelTGLGraphicsFramebuffer.kext/Contents/MacOS/AppleIntelTGLGraphicsFramebuffer'
KERNEL = ROOT / 'kernel-evidence-readonly-20261023-221944/copies/system/System/Library/Kernels/kernel'
OUT = ROOT / 'yoga-cursor-diag'


def image(path):
    data = path.read_bytes()
    assert struct.unpack_from('<I', data)[0] == 0xfeedfacf
    segments = []
    offset = 32
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        cmd, size = struct.unpack_from('<II', data, offset)
        assert size >= 8 and offset + size <= len(data)
        if cmd == 0x19:
            _, address, _, fileoff, filesize = struct.unpack_from('<16sQQQQ', data, offset + 8)
            segments.append((address, fileoff, filesize))
        offset += size

    def at(address, length):
        for start, fileoff, filesize in segments:
            if start <= address and address + length <= start + filesize:
                return data[fileoff + address - start:fileoff + address - start + length]
        raise ValueError(hex(address))
    return data, at


def main():
    data, at = image(FB)
    assert hashlib.sha256(data).hexdigest() == '3f2bb3336507242ddc3f69c5d7645d19ce1cd4d8748bdb4b4c8858c4b49103df'
    kd, kat = image(KERNEL)
    assert hashlib.sha256(kd).hexdigest() == '7004ebc1020a5c7e3f075c631507f31fdc0ce3fe02e9f01f42dce1d178770a08'
    funcs = [
        ('Image', 0x7dac2, '__ZN24AppleIntelBaseController16hwSetCursorImageEP21AppleIntelFramebufferP20IOHardwareCursorInfo'),
        ('Scale', 0x7d40a, '__ZN24AppleIntelBaseController18hwScaleCursorImageEP21AppleIntelFramebufferP20IOHardwareCursorInfoPVjPjS6_'),
        ('State', 0x7dff8, '__ZN24AppleIntelBaseController16hwSetCursorStateEP21AppleIntelFramebufferiibb'),
        ('Memory', 0x7ec18, '__ZN24AppleIntelBaseController20hwUpdateCursorMemoryEP21AppleIntelFramebuffer'),
        ('Params', 0x7eb2c, '__ZN24AppleIntelBaseController18updateCursorParamsEP21AppleIntelFramebufferP21AppleIntelDisplayPath'),
    ]
    # Assert non-prologue evidence for return ABI, conversion, buffer selection,
    # path/register-offset fields and allocation bounds. All from this binary.
    checks = {
        0x7dfe7: '89 d8',  # IOReturn, not bool
        0x7e190: '31 c0',  # state IOReturn zero
        0x7dd29: '41 8b 87 d8 4a 00 00 f7 d0 83 e0 01',
        0x7dd3c: 'f7 d0 83 e0 01 41 89 87 d8 4a 00 00',
        0x7dd50: '41 2b 85 c0 0d 00 00 83 e0 fc 48 01 c3',
        0x7dde0: '81 fe ff ff ff 00',
        0x7ddf2: 'be 00 00 00 0f',
        0x7ec06: '45 89 be 70 01 00 00',
        0x7ecb8: '8b 89 40 36 00 00 c1 e1 13',
        0x5c665: '41 83 bd c8 0d 00 00 00',
    }
    for address, expected in checks.items():
        expected = bytes.fromhex(expected)
        assert at(address, len(expected)) == expected, hex(address)
    symbols = subprocess.check_output(['llvm-nm', '--defined-only', '--format=posix', str(FB)], text=True)
    addresses = {parts[0]: int(parts[2], 16) for line in symbols.splitlines()
                 if len(parts := line.split()) == 4}
    for _, address, symbol in funcs:
        assert addresses[symbol] == address
    sets = plistlib.loads((ROOT / 'kernel-evidence-readonly-20261023-221944/kernel-symbolsets.plist').read_bytes())
    strings = []

    def walk(value):
        if isinstance(value, str):
            strings.append(value)
        elif isinstance(value, dict):
            for key, item in value.items():
                walk(key)
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(sets)
    exported = any('ml_nofault_copy' in s for s in strings)
    assert not exported, 'Revisit dynamic resolution design if export set changed'
    OUT.mkdir(exist_ok=True)
    header = ['// Generated by audit_cursor_diag_inputs.py from hash-checked captured files.']
    for name, address, symbol in funcs:
        header += [f'static const char sym{name}[] = "{symbol}";',
                   f'static const uint8_t guard{name}[] = {{' + ','.join(f'0x{b:02x}' for b in at(address, 48)) + '};']
    nf = kat(0xffffff80003e4dc0, 32)
    assert nf.hex().startswith('554889e54157415641554154534883ec18')
    header.append('static const uint8_t guardNoFault[] = {' + ','.join(f'0x{b:02x}' for b in nf) + '};')
    (OUT / 'CursorGuards.hpp').write_text('\n'.join(header) + '\n')
    disasm = subprocess.check_output(['llvm-objdump', '-d', '--x86-asm-syntax=intel',
        '--start-address=0xffffff80003e4dc0', '--stop-address=0xffffff80003e4f30', str(KERNEL)], text=True)
    (OUT / 'captured-ml_nofault_copy.disasm.txt').write_text(disasm)
    report = dict(framebuffer_sha256=hashlib.sha256(data).hexdigest(),
                  kernel_sha256=hashlib.sha256(kd).hexdigest(),
                  sites=[dict(name=n, address=hex(a), symbol=s) for n, a, s in funcs],
                  byte_assertions=len(checks), nofault_in_captured_symbolsets=exported,
                  nofault_semantics='vm_size_t(vm_offset_t src, vm_offset_t dst, vm_size_t length); byte count; wired translations assumed, no lifetime guarantee; rejects non-pmap-valid RAM',
                  runtime_guard='48 bytes at each cursor entry plus 32 bytes at dynamically resolved nofault entry; not a runtime whole-file hash',
                  external_writes=False, runtime_validated=False)
    (OUT / 'input-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
